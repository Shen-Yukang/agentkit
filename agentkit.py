def hook_pre_commit(root: Path, cfg: dict) -> int:
    """git pre-commit: works for every agent and every person, not just Claude Code."""
    staged = git_paths(root, "diff", "--cached", "--name-only")
    code = [f for f in staged if not f.startswith(tasks_prefix(cfg))]
    if not code:
        return 0
    task_id, _ = current_task(root, cfg)
    if not task_id:
        if cfg["tasks_required"]:
            print(t(f"agentkit：本仓库要求每个改动都有任务卡（agentkit.toml 的 tasks.required），这次提交改了代码，但没有当前任务卡。"
                    f"先运行 `{CLI} task new <任务号> <标题>` 并请人确认，或用 `{CLI} task use <任务号>` 指定。",
                    "agentkit: this repository requires a task card for every change (tasks.required in agentkit.toml); "
                    "this commit changes code but there is no current task card. "
                    f"First run `{CLI} task new <task-id> <title>` and ask a person to confirm, "
                    f"or pick the card with `{CLI} task use <task-id>`."), file=sys.stderr)
            return 1
        print(t(f"agentkit 提醒：这次提交改了代码，但没有当前任务卡（`{CLI} task show`）。",
                f"agentkit reminder: this commit changes code but there is no current task card (`{CLI} task show`)."),
              file=sys.stderr)
        return 0
    rel = os.path.relpath(card_path(root, cfg, task_id), root).replace(os.sep, "/")
    committed = subprocess.run(["git", "-C", str(root), "show", f":{rel}"], capture_output=True, text=True)
    if committed.returncode != 0:
        print(t(f"agentkit：任务卡 {rel} 还没有加入 git，先运行 `git add {rel}`，和代码一起提交。",
                f"agentkit: the task card {rel} is not in git yet; run `git add {rel}` and commit it with the code."),
              file=sys.stderr)
        return 1
    if card_status(committed.stdout)["confirmed"] != "yes":
        print(t(f"agentkit：要提交的任务卡（暂存区里的 {rel}）显示任务 {task_id} 的需求还没有人确认（或确认后又改过），先不提交代码。"
                f"请人运行 `{CLI} task confirm {task_id}`，再 `git add {rel}`；"
                f"如果这次提交不属于这个任务，运行 `{CLI} task use --clear`。",
                f"agentkit: the task card being committed (the staged {rel}) shows that nobody has confirmed the requirement "
                f"of task {task_id} (or it changed after it was confirmed), so the code is not committed yet. "
                f"Ask a person to run `{CLI} task confirm {task_id}`, then `git add {rel}`; "
                f"if this commit is not part of that task, run `{CLI} task use --clear`."), file=sys.stderr)
        return 1
    return 0


GIT_HOOK_LINE = "python3 .agentkit/agentkit.py hook pre-commit"
GIT_HOOK_GUARDED = f"[ ! -f .agentkit/agentkit.py ] || {GIT_HOOK_LINE}  # agentkit：需求没确认前不提交代码"
GIT_HOOK_GUARDED_EN = f"[ ! -f .agentkit/agentkit.py ] || {GIT_HOOK_LINE}  # agentkit: no code commits before the requirement is confirmed"
SHIPPED_HOOK_DIRS = (".githooks", ".husky")


def add_to_hook(path: Path) -> bool:
    """Add the kit's line to a hook the repository ships; before a final exec, which would never return."""
    text = path.read_text()
    if GIT_HOOK_LINE in text:
        return False
    lines = text.rstrip("\n").split("\n")
    at = len(lines) - 1 if lines and lines[-1].lstrip().startswith("exec ") else len(lines)
    lines.insert(at, t(GIT_HOOK_GUARDED, GIT_HOOK_GUARDED_EN))
    path.write_text("\n".join(lines) + "\n")
    return True


def install_git_hook(root: Path) -> str:
    """Hook the kit into git commits. Returns what happened, for the install report.

    A repository that ships its own hooks (core.hooksPath, .githooks/, .husky/) gets one line in its pre-commit,
    so everyone who enables the repository's hooks gets the check; .git/hooks is left alone so the repository's
    own installer is not blocked. Otherwise the hook goes into this clone's .git/hooks.
    """
    custom = subprocess.run(["git", "-C", str(root), "config", "core.hooksPath"], capture_output=True, text=True).stdout.strip()
    guarded = t(GIT_HOOK_GUARDED, GIT_HOOK_GUARDED_EN)
    shipped = None
    if custom:
        candidate = (Path(custom) if os.path.isabs(custom) else root / custom).resolve() / "pre-commit"
        if candidate.is_file() and candidate.is_relative_to(root.resolve()):
            shipped = candidate
        else:
            return t(f"git 钩子目录是 {custom}：请在其中的 pre-commit 里加一行 `{guarded}`",
                     f"git hooks live in {custom}: add the line `{guarded}` to the pre-commit there")
    else:
        shipped = next((root / d / "pre-commit" for d in SHIPPED_HOOK_DIRS if (root / d / "pre-commit").is_file()), None)
    if shipped:
        rel = os.path.relpath(shipped, root)
        if not add_to_hook(shipped):
            return ""
        return t(f"在仓库自带的 {rel} 里加了一行 agentkit 检查；按仓库自己的方式启用 git 钩子后生效",
                 f"added an agentkit check line to the repository's own {rel}; it takes effect once git hooks are "
                 "enabled the repository's way")
    hooks = Path(git(root, "rev-parse", "--git-path", "hooks").strip())
    hook = (hooks if hooks.is_absolute() else root / hooks) / "pre-commit"
    if hook.exists():
        if GIT_HOOK_LINE in hook.read_text(errors="ignore"):
            return ""
        existing = os.path.relpath(hook, root)
        return t(f"已有 {existing}：请在里面加一行 `{guarded}`", f"{existing} already exists: add the line `{guarded}` to it")
    hook.parent.mkdir(parents=True, exist_ok=True)
    note = t(f"{OWNED}：需求没确认前不提交代码", f"{OWNED_EN}: no code commits before the requirement is confirmed")
    hook.write_text(f"#!/bin/sh\n# {note}\nexec {GIT_HOOK_LINE}\n")
    hook.chmod(0o755)
    return t(f"已安装 git pre-commit 钩子（只对这个克隆生效；其他人运行 `{CLI} hook install-git`）",
             f"installed the git pre-commit hook (this clone only; everyone else runs `{CLI} hook install-git`)")


