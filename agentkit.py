class _TomlReader:
    """Enough TOML for agentkit.toml: tables, arrays of tables, strings, numbers, booleans, arrays, inline tables."""

    KEY = re.compile(r"[A-Za-z0-9_-]+")
    NUMBER = re.compile(r"[+-]?[0-9][0-9_]*(\.[0-9_]+)?([eE][+-]?[0-9]+)?")
    ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "b": "\b", "f": "\f", '"': '"', "\\": "\\"}

    def __init__(self, text: str):
        self.s, self.i = text, 0

    def fail(self, message: str):
        line = self.s.count(chr(10), 0, self.i) + 1
        raise ValueError(t(f"agentkit.toml 第 {line} 行：{message}", f"agentkit.toml line {line}: {message}"))

    def peek(self, n: int = 1) -> str:
        return self.s[self.i:self.i + n]

    def skip(self, newlines: bool = False) -> None:
        while self.i < len(self.s):
            c = self.s[self.i]
            if c in " \t\r" or (newlines and c == "\n"):
                self.i += 1
            elif c == "#":
                while self.i < len(self.s) and self.s[self.i] != "\n":
                    self.i += 1
            else:
                break

    def expect(self, token: str) -> None:
        if not self.s.startswith(token, self.i):
            self.fail(t(f"这里应该是 {token}", f"expected {token} here"))
        self.i += len(token)

    def parse(self) -> dict:
        root: dict = {}
        current = root
        while True:
            self.skip(newlines=True)
            if self.i >= len(self.s):
                return root
            if self.peek(2) == "[[":
                self.i += 2
                keys = self.keys()
                self.expect("]]")
                items = self.descend(root, keys[:-1]).setdefault(keys[-1], [])
                if not isinstance(items, list):
                    self.fail(t(f"{keys[-1]} 已经定义成了别的类型", f"{keys[-1]} is already defined as something else"))
                current = {}
                items.append(current)
            elif self.peek() == "[":
                self.i += 1
                keys = self.keys()
                self.expect("]")
                current = self.descend(root, keys)
            else:
                keys = self.keys()
                self.expect("=")
                self.skip()
                self.descend(current, keys[:-1])[keys[-1]] = self.value()
            self.skip()
            if self.i < len(self.s) and self.s[self.i] != "\n":
                self.fail(t("这一行后面有多余的内容", "unexpected text after the value"))

    def descend(self, table: dict, keys: list[str]) -> dict:
        for key in keys:
            nxt = table.setdefault(key, {})
            if isinstance(nxt, list) and nxt:
                nxt = nxt[-1]
            if not isinstance(nxt, dict):
                self.fail(t(f"{key} 不是表", f"{key} is not a table"))
            table = nxt
        return table

    def keys(self) -> list[str]:
        out = []
        while True:
            self.skip()
            if self.peek() == '"':
                out.append(self.basic())
            elif self.peek() == "'":
                out.append(self.literal())
            else:
                m = self.KEY.match(self.s, self.i)
                if not m:
                    self.fail(t("缺少键名", "missing key"))
                out.append(m.group())
                self.i = m.end()
            self.skip()
            if self.peek() != ".":
                return out
            self.i += 1

    def value(self):
        if self.peek(3) in ('"""', "'''"):
            return self.multiline()
        c = self.peek()
        if c == '"':
            return self.basic()
        if c == "'":
            return self.literal()
        if c == "[":
            return self.array()
        if c == "{":
            return self.table()
        for word, val in (("true", True), ("false", False)):
            if self.s.startswith(word, self.i):
                self.i += len(word)
                return val
        m = self.NUMBER.match(self.s, self.i)
        if not m:
            self.fail(t("看不懂的值", "invalid value"))
        self.i = m.end()
        text = m.group().replace("_", "")
        return float(text) if m.group(1) or m.group(2) else int(text)

    def unescape(self, raw: str) -> str:
        def one(m: re.Match) -> str:
            body = m.group(1)
            if body[0] in "uU":
                return chr(int(body[1:], 16))
            if body in self.ESCAPES:
                return self.ESCAPES[body]
            self.fail(t(f"不认识的转义 \\{body}", f"unknown escape \\{body}"))
        return re.sub(r"\\(u[0-9a-fA-F]{4}|U[0-9a-fA-F]{8}|.)", one, raw)

    def basic(self) -> str:
        m = re.compile(r'"((?:[^"\\\n]|\\.)*)"').match(self.s, self.i)
        if not m:
            self.fail(t("字符串没有结束", "unterminated string"))
        self.i = m.end()
        return self.unescape(m.group(1))

    def literal(self) -> str:
        end = self.s.find("'", self.i + 1)
        if end == -1 or "\n" in self.s[self.i + 1:end]:
            self.fail(t("字符串没有结束", "unterminated string"))
        value, self.i = self.s[self.i + 1:end], end + 1
        return value

    def multiline(self) -> str:
        quote = self.peek(3)
        self.i += 3
        if self.peek() == "\n":
            self.i += 1
        end = self.s.find(quote, self.i)
        if end == -1:
            self.fail(t("多行字符串没有结束", "unterminated multi-line string"))
        raw, self.i = self.s[self.i:end], end + 3
        return raw if quote == "'''" else self.unescape(re.sub(r"\\[ \t]*\n\s*", "", raw))

    def array(self) -> list:
        self.i += 1
        items = []
        while True:
            self.skip(newlines=True)
            if self.peek() == "]":
                self.i += 1
                return items
            items.append(self.value())
            self.skip(newlines=True)
            if self.peek() == ",":
                self.i += 1
            elif self.peek() != "]":
                self.fail(t("数组里缺少逗号", "missing comma in array"))

    def table(self) -> dict:
        self.i += 1
        out: dict = {}
        self.skip()
        if self.peek() == "}":
            self.i += 1
            return out
        while True:
            keys = self.keys()
            self.expect("=")
            self.skip()
            self.descend(out, keys[:-1])[keys[-1]] = self.value()
            self.skip()
            if self.peek() == "}":
                self.i += 1
                return out
            self.expect(",")


def parse_toml(text: str) -> dict:
    return _TomlReader(text).parse()


def matches(path: str, pattern: str) -> bool:
    path = path.removeprefix("./")
    if pattern.endswith("/"):
        return path.startswith(pattern)
    if any(ch in pattern for ch in "*?["):
        return fnmatch.fnmatchcase(path, pattern)
    return path == pattern or path.startswith(pattern + "/")


def matching(files: list[str], patterns: list[str]) -> list[str]:
    return [f for f in files if any(matches(f, p) for p in patterns)]


# ---------------------------------------------------------------- git

def git(root: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, check=True).stdout


def ref_exists(root: Path, ref: str) -> bool:
    return subprocess.run(["git", "-C", str(root), "rev-parse", "--verify", "--quiet", ref],
                          capture_output=True).returncode == 0


def default_base(root: Path) -> str:
    for ref in ("origin/main", "main", "origin/master", "master"):
        if ref_exists(root, ref):
            return ref
    return "HEAD"


def git_paths(root: Path, command: str, *args: str) -> list[str]:
    """File names from git, NUL-separated so names with spaces or non-ASCII characters come through intact."""
    return [p for p in git(root, command, "-z", *args).split("\0") if p]


def changed_files(root: Path, base: str, worktree: bool = True) -> list[str]:
    files: set[str] = set()
    if base != "HEAD":
        files |= set(git_paths(root, "diff", "--name-only", f"{base}...HEAD"))
    if worktree:
        files |= set(git_paths(root, "diff", "--name-only", "HEAD"))
        files |= set(git_paths(root, "ls-files", "--others", "--exclude-standard"))
    return sorted(files)


# ---------------------------------------------------------------- checks

def plan_checks(cfg: dict, files: list[str]) -> list[tuple[str, str]]:
    plan = [(cmd, t("每次都跑", "always")) for cmd in cfg["checks_always"]]
    seen = {cmd for cmd, _ in plan}
    for entry in cfg["checks_by_path"]:
        hit = matching(files, entry["paths"])
        if not hit:
            continue
        more = len(hit) > 1
        reason = t(f"改到 {hit[0]}" + (f" 等 {len(hit)} 个文件" if more else ""),
                   f"{hit[0]} changed" + (f" (and {len(hit) - 1} more)" if more else ""))
        for cmd in entry["run"]:
            if cmd not in seen:
                plan.append((cmd, reason))
                seen.add(cmd)
    return plan


def run_checks(root: Path, plan: list[tuple[str, str]], timeout: int) -> list[dict]:
    results = []
    for cmd, reason in plan:
        start = time.monotonic()
        try:
            proc = subprocess.run(cmd, shell=True, cwd=root, capture_output=True, text=True, timeout=timeout)
            code, output = proc.returncode, proc.stdout + proc.stderr
        except subprocess.TimeoutExpired:
            code, output = 124, t(f"超时（超过 {timeout} 秒）", f"timed out (over {timeout} seconds)")
        results.append({"cmd": cmd, "reason": reason, "code": code,
                        "seconds": round(time.monotonic() - start, 1),
                        "tail": "\n".join(output.strip().splitlines()[-30:])})
    return results


def evidence_md(base: str, head: str, files: list[str], results: list[dict], uncovered: list[str]) -> str:
    lines = [t("### 自动检查（agentkit checks）", "### Automatic checks (agentkit checks)"), "",
             t(f"对比：`{base}` → `{head}`；改动文件 {len(files)} 个。",
               f"Compared: `{base}` → `{head}`; {len(files)} file(s) changed."), ""]
    if not results:
        lines.append(t("agentkit.toml 里没有配置任何检查。", "No checks are configured in agentkit.toml."))
    else:
        lines += [t("| 命令 | 为什么跑 | 结果 | 用时 |", "| Command | Why it ran | Result | Time |"), "|---|---|---|---|"]
        for r in results:
            if r["code"] == 0:
                verdict = t("通过", "passed")
            else:
                verdict = t(f"**失败**（退出码 {r['code']}）", f"**failed** (exit code {r['code']})")
            lines.append(f"| `{r['cmd']}` | {r['reason']} | {verdict} | {r['seconds']}s |")
        for r in results:
            if r["code"] != 0:
                summary = t(f"<code>{r['cmd']}</code> 的最后 30 行输出", f"Last 30 lines of <code>{r['cmd']}</code>")
                lines += ["", f"<details><summary>{summary}</summary>", "",
                          "```text", r["tail"], "```", "", "</details>"]
    if uncovered:
        shown = join_items(f"`{f}`" for f in uncovered[:5])
        if len(uncovered) > 5:
            shown += t(f" 等 {len(uncovered)} 个", f" and {len(uncovered) - 5} more")
        lines += ["", t(f"没有专门检查覆盖的改动：{shown}（只跑了每次都跑的检查）。",
                        f"Changes no specific check covers: {shown} (only the always-run checks ran).")]
    return "\n".join(lines) + "\n"


