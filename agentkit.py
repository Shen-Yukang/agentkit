    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a") as f:
            f.write(comment.split("<!--")[0])
    if not decision["passed"]:
        blockers = len(decision["blockers"])
        print(t(f"不通过：{blockers} 个已确认的 Important 问题。", f"Fails: {blockers} confirmed Important issue(s)."), file=sys.stderr)
        return 1
    return 0


