def risk_floor(cfg: dict, files: list[str]) -> dict:
    protected = matching(files, cfg["protected"])
    high = matching(files, cfg["high_risk"])
    return {"floor": "high" if protected or high else "low", "protected": protected, "high_risk": high}


def parse_result(text: str) -> tuple[dict | None, list[str]]:
    blocks = RESULT_RE.findall(text)
    if not blocks:
        return None, [t("没有找到 ai-review-result 段", "no ai-review-result block found")]
    try:
        result = json.loads(blocks[-1])
    except json.JSONDecodeError as e:
        return None, [t(f"ai-review-result 不是合法的 JSON：{e}", f"ai-review-result is not valid JSON: {e}")]
    if not isinstance(result, dict):
        return None, [t("ai-review-result 必须是一个 JSON 对象", "ai-review-result must be a JSON object")]
    errors = []
    scores = result.get("scores")
    if not isinstance(scores, dict):
        errors.append(t("scores 必须是对象", "scores must be an object"))
    else:
        for key in SCORE_KEYS:
            value = scores.get(key)
            if value is None and key == "requirement":
                continue
            if isinstance(value, bool) or not isinstance(value, int) or not 1 <= value <= 5:
                errors.append(t(f"scores.{key} 必须是 1–5 的整数", f"scores.{key} must be an integer from 1 to 5"))
    if result.get("risk_level") not in RISK_ORDER:
        errors.append(t("risk_level 只能是 low、medium、high", "risk_level must be low, medium or high"))
    issues = result.get("issues")
    if not isinstance(issues, list):
        errors.append(t("issues 必须是列表", "issues must be a list"))
    else:
        for i, issue in enumerate(issues):
            if not isinstance(issue, dict):
                errors.append(t(f"issues[{i}] 必须是对象", f"issues[{i}] must be an object"))
                continue
            if not isinstance(issue.get("file"), str) or not issue["file"]:
                errors.append(t(f"issues[{i}].file 必须是文件路径", f"issues[{i}].file must be a file path"))
            line = issue.get("line")
            if line is not None and (isinstance(line, bool) or not isinstance(line, int)):
                errors.append(t(f"issues[{i}].line 必须是整数或 null", f"issues[{i}].line must be an integer or null"))
            if issue.get("severity") not in SEVERITIES:
                errors.append(t(f"issues[{i}].severity 只能是 important、nit、pre-existing",
                                  f"issues[{i}].severity must be important, nit or pre-existing"))
            if not isinstance(issue.get("confirmed"), bool):
                errors.append(t(f"issues[{i}].confirmed 必须是 true 或 false", f"issues[{i}].confirmed must be true or false"))
            if not isinstance(issue.get("summary"), str) or not issue["summary"].strip():
                errors.append(t(f"issues[{i}].summary 不能为空", f"issues[{i}].summary must not be empty"))
    return result, errors


def decide(cfg: dict, review: dict, floor: dict, prior_rounds: int) -> dict:
    final = max(review["risk_level"], floor["floor"], key=RISK_ORDER.index)
    important = [i for i in review["issues"] if i["severity"] == "important"]
    blockers = [i for i in important if i["confirmed"]]
    round_ = prior_rounds + 1
    labels = [f"risk:{final}"] + (["needs-human"] if round_ >= 3 and blockers else [])
    return {"round": round_, "risk_level": final, "ai_risk_level": review["risk_level"], "floor": floor,
            "reviewers_needed": int(cfg["reviewers"].get(final, 0)), "blockers": blockers,
            "unconfirmed": [i for i in important if not i["confirmed"]], "labels": labels,
            "passed": not blockers}


def finalize_comment(text: str, review: dict, decision: dict, head: str) -> str:
    result = {**review, "head": head, "round": decision["round"], "risk_level": decision["risk_level"],
              "ai_risk_level": decision["ai_risk_level"], "reviewers_needed": decision["reviewers_needed"]}
    body = RESULT_RE.sub("", text).rstrip()
    floor = decision["floor"]
    why = ""
    if decision["risk_level"] != decision["ai_risk_level"]:
        hits = join_items(f"`{h}`" for h in (floor["protected"] + floor["high_risk"])[:3])
        ai = risk_word(decision["ai_risk_level"])
        why = t(f"（AI 初判为{ai}；按 agentkit.toml 的路径规则上调：改到 {hits}）",
                f" (the AI said {ai}; raised by the path rules in agentkit.toml: changes {hits})")
    blockers, unconfirmed = len(decision["blockers"]), len(decision["unconfirmed"])
    if decision["passed"]:
        verdict = t("没有已确认的 Important 问题，检查通过", "no confirmed Important issues, passes")
    else:
        verdict = t(f"有 {blockers} 个已确认的 Important 问题，修复前不通过",
                    f"{blockers} confirmed Important issue(s), does not pass until fixed")
    if unconfirmed:
        verdict += t(f"；另有 {unconfirmed} 个待确认的 Important，请人判断",
                     f"; {unconfirmed} more unconfirmed Important issue(s) for a person to judge")
    round_, risk, needed = decision["round"], risk_word(decision["risk_level"]), decision["reviewers_needed"]
    footer = t(f"\n\n---\n**agentkit 判定**（第 {round_} 轮，head `{head[:7]}`）：风险 **{risk}**{why}；建议 {needed} 人审；{verdict}。",
               f"\n\n---\n**agentkit verdict** (round {round_}, head `{head[:7]}`): risk **{risk}**{why}; "
               f"suggested human reviewers: {needed}; {verdict}.")
    if "needs-human" in decision["labels"]:
        footer += t("\n已经是第 3 轮以上仍有阻塞问题：加上 `needs-human`，建议换个思路或找人当面讨论。",
                    "\nRound 3 or later and still blocked: added `needs-human`. Try another approach or talk it through in person.")
    block = "<!-- ai-review-result\n" + json.dumps(result, ensure_ascii=False) + "\n-->"
    return body + footer + "\n\n" + block + "\n"


# ---------------------------------------------------------------- task cards
#
# One Markdown file per task, shared by people and every agent: the requirement (three questions),
# the human sign-off, decisions only people make, the split, and the handoff. Agents read it when
# they start and update it before they stop, so work survives a new chat, a new agent or a new person.

def template_root() -> Path:
    """The kit repository's templates in the repository's language: templates/ (Chinese) or templates/en/."""
    return KIT_DIR / "templates" / "en" if UI_LANG == "en" else KIT_DIR / "templates"


def kit_file(*parts: str) -> Path:
    """A kit file: next to an installed agentkit.py (.agentkit/..., installed in the repository's language),
    or under the templates in the kit repo."""
    installed = KIT_DIR.joinpath(*parts)
    return installed if installed.exists() else template_root().joinpath(*parts)


def strip_comments(text: str) -> str:
    return re.sub(r"<!--.*?-->", "", text, flags=re.S)


def card_sections(text: str) -> dict[str, str]:
    sections: dict[str, str] = {}
    current = None
    for line in strip_comments(text).splitlines():
        heading = re.match(r"^##\s+(.+?)\s*$", line)
        if heading:
            current = heading.group(1)
            sections[current] = ""
        elif current is not None:
            sections[current] += line + "\n"
    return sections


def section_of(sections: dict[str, str], name: str) -> str:
    """A section's text, by its Chinese name, in a card written in either language."""
    wanted = {name.lower(), CARD_NAMES.get(name, name).lower()}
    return next((body for heading, body in sections.items() if heading.lower() in wanted), "")


def card_language(text: str) -> str:
    """The language a card is written in, from its headings. agentkit writes into a card in the card's language."""
    for heading in card_sections(text):
        for zh, en in CARD_NAMES.items():
            if heading == zh:
                return "zh"
            if heading.lower() == en.lower():
                return "en"
    return UI_LANG


def field_line(name: str) -> re.Pattern:
    """A "- name：value" line. The name may be bold or carry a note: "- **怎么算做完**（可检查）：…"."""
    gap = r"[ \t]*"  # never \s: a match must not run into the next line
    return re.compile(rf"^({gap}[-*]{gap})\**{name_pattern(name)}\**{gap}(?:[（(][^）)\n]*[）)])?{gap}\**{gap}[：:]{gap}\**{gap}([^\n]*)$",
                      re.M | re.I)


def field_value(section: str, name: str) -> str:
    """The text after "- name：", plus any indented lines under it."""
    lines = section.splitlines()
    pattern = field_line(name)
    for i, line in enumerate(lines):
        m = pattern.match(line)
        if not m:
            continue
        parts = [m.group(2).strip()]
        for nxt in lines[i + 1:]:
            if not nxt.strip() or not nxt[0].isspace():
                break
            parts.append(nxt.strip())
        return " ".join(p for p in parts if p).strip()
    return ""


def requirement_fingerprint(section: str) -> str:
    """Hash of the requirement without the sign-off line: any later edit makes the sign-off stale."""
    kept = [line for line in section.splitlines() if not field_line("确认").match(line)]
    normalized = re.sub(r"\s+", " ", "\n".join(kept)).strip()
    return hashlib.sha256(normalized.encode()).hexdigest()[:8]


def card_status(text: str) -> dict:
    secs = card_sections(text)
    lang = card_language(text)
    req = section_of(secs, "需求")
    confirm = field_value(req, "确认")
    fp = FINGERPRINT_RE.search(confirm)
    if not confirm:
        confirmed = "no"
    elif fp and fp.group(1) == requirement_fingerprint(req):
        confirmed = "yes"
    else:
        confirmed = "stale"
    decisions = section_of(secs, "要人拍板的事")
    steps = re.findall(r"(?m)^\s*(?:[-*]|\d+[.)])\s*\[(todo|doing|done)\]\s*(.*)$", section_of(secs, "拆分"))
    handoff = section_of(secs, "交接")
    title = next((line[2:].strip() for line in text.splitlines() if line.startswith("# ")), "")
    return {
        "title": title,
        "lang": lang,
        "missing": [card_name(f, lang) for f in TASK_FIELDS if not field_value(req, f)],
        "confirmed": confirmed,
        "confirmed_by": re.sub(r"[（(](?:需求指纹|(?i:requirement fingerprint)).*?[）)]", "", confirm).strip(),
        "open": [item.strip() for item in re.findall(r"(?m)^\s*[-*]\s*\[ \]\s*(.+)$", decisions)],
        "decided": len(re.findall(r"(?m)^\s*[-*]\s*\[[xX]\]", decisions)),
        "steps": [(state, name.strip()) for state, name in steps],
        "handoff": {k: field_value(handoff, k) for k in HANDOFF_FIELDS},
        "handoff_text": re.sub(r"\s+", " ", handoff).strip(),
    }


def status_lines(task_id: str, st: dict) -> list[str]:
    confirm = f"`{CLI} task confirm {task_id}`"
    missing = join_items(quoted(f) for f in st["missing"])
    lines = [t("- 需求：" + ("三问都写了" if not st["missing"] else f"还缺 {missing}"),
               "- Requirement: " + ("all three answered" if not st["missing"] else f"missing {missing}"))]
    if st["confirmed"] == "yes":
        lines.append(t(f"- 确认：{st['confirmed_by']}", f"- Sign-off: {st['confirmed_by']}"))
    elif st["confirmed"] == "stale":
        lines.append(t(f"- 确认：**已失效**，确认之后需求又改过，请人重新运行 {confirm}",
                       f"- Sign-off: **stale**, the requirement changed after it was confirmed; a person must run {confirm} again"))
    else:
        lines.append(t(f"- 确认：**还没有**。先把复述写进任务卡，再请人运行 {confirm}",
                       f"- Sign-off: **not yet**. Write the restatement into the task card first, then ask a person to run {confirm}"))
    if st["open"]:
        count = len(st["open"])
        shown = t("；", "; ").join(st["open"][:3]) + (t(" 等", " and more") if count > 3 else "")
        lines.append(t(f"- 要人拍板：还有 {count} 件没定：{shown}", f"- Decisions: {count} still open: {shown}"))
    else:
        lines.append(t("- 要人拍板：没有待定的事" + (f"（已定 {st['decided']} 件）" if st["decided"] else ""),
                       "- Decisions: none open" + (f" ({st['decided']} decided)" if st["decided"] else "")))
    if st["steps"]:
        done, total = sum(1 for state, _ in st["steps"] if state == "done"), len(st["steps"])
        doing = [name for state, name in st["steps"] if state == "doing"]
        lines.append(t(f"- 拆分：完成 {done}/{total}" + (f"；正在做：{doing[0]}" if doing else ""),
                       f"- Steps: {done}/{total} done" + (f"; doing: {doing[0]}" if doing else "")))
    else:
        lines.append(t("- 拆分：还没拆", "- Steps: none yet"))
    nxt, handoff = st["handoff"]["下一步"], quoted(card_name("交接", st["lang"]))
    if nxt:
        lines.append(t(f"- 下一步：{nxt}", f"- Next step: {nxt}"))
    else:
        lines.append(t(f"- 下一步：（{handoff}里还没写）", f"- Next step: (not written under {handoff} yet)"))
    return lines


def rule_reminder(st: dict) -> str:
    if st["confirmed"] != "yes":
        return t("按约定：需求被人确认之前，除了这张任务卡，不要改别的文件。",
                 "As agreed: until a person confirms the requirement, change no file other than this task card.")
    steps, handoff = (quoted(card_name(n, st["lang"])) for n in ("拆分", "交接"))
    return t(f"按约定：一次只做{steps}里的一块，做完运行 `{CLI} checks` 拿证据；"
             f"收工前更新{handoff}，再运行 `{CLI} task handoff --agent <你是哪个 agent>`。",
             f"As agreed: do one item of {steps} at a time and run `{CLI} checks` for evidence when it is done; "
             f"before you stop, update {handoff}, then run `{CLI} task handoff --agent <which agent you are>`.")


def tasks_prefix(cfg: dict) -> str:
    return cfg["tasks_dir"] + "/"


def card_path(root: Path, cfg: dict, task_id: str) -> Path:
    return root / cfg["tasks_dir"] / f"{task_id}.md"


def card_ids(root: Path, cfg: dict) -> list[str]:
    folder = root / cfg["tasks_dir"]
    if not folder.is_dir():
        return []
    return sorted(p.stem for p in folder.glob("*.md") if p.name.lower() != "readme.md")


def card_files(cfg: dict, files: list[str]) -> list[str]:
    prefix = tasks_prefix(cfg)
    return [f for f in files if f.startswith(prefix) and f.endswith(".md")
            and "/" not in f[len(prefix):] and f.lower() != (prefix + "readme.md").lower()]


def ids_in(text: str, ids: list[str]) -> list[str]:
    """Task ids named in text. WIP-16 is not named by "WIP-16-3-x": a -<digit> after it makes a different id."""
    return [i for i in ids if re.search(rf"(?<![A-Za-z0-9]){re.escape(i)}(?![A-Za-z0-9])(?!-[0-9])", text)]


def current_task(root: Path, cfg: dict, explicit: str | None = None, base: str | None = None) -> tuple[str | None, str]:
    """Find this session's task card: given id, then this clone's pointer, the branch name, the cards changed on the branch."""
    ids = card_ids(root, cfg)
    if explicit:
        task_id = Path(explicit).stem if explicit.endswith(".md") else explicit
        if task_id in ids:
            return task_id, t("命令行指定", "given on the command line")
        return None, t(f"找不到任务卡 {cfg['tasks_dir']}/{task_id}.md", f"no task card {cfg['tasks_dir']}/{task_id}.md")
    try:
        branch = current_branch(root)
        pointed = read_pointer(root)
        if pointed and pointed[0] in ids and pointed[1] in ("", branch):
            return pointed[0], t("当前任务（task new / task use 设置的）", "set as current by task new / task use")
        hit = ids_in(branch, ids)
        if len(hit) == 1:
            return hit[0], t(f"分支名 {branch}", f"branch name {branch}")
        changed = [Path(f).stem for f in card_files(cfg, changed_files(root, base or default_base(root)))]
    except subprocess.CalledProcessError:
        return None, ""
    changed = [c for c in changed if c in ids]
    if len(changed) == 1:
        return changed[0], t("这个分支改过的任务卡", "the task card changed on this branch")
    return None, ""


def no_task_text(root: Path, cfg: dict) -> str:
    ids = card_ids(root, cfg)
    if ids:
        known = join_items(ids[:10]) + (t(" 等", " and more") if len(ids) > 10 else "")
        existing = t(f"已有的任务卡：{known}", f"Existing task cards: {known}")
    else:
        existing = t("现在还没有任务卡。", "There are no task cards yet.")
    return "\n".join([
        t("没有找到当前任务的任务卡。", "No task card found for the current task."),
        t(f"- 新任务：运行 `{CLI} task new <任务号> <一句话标题>`，把复述写进任务卡，请人确认。",
          f"- New task: run `{CLI} task new <task-id> <one-line title>`, write the restatement into the card "
          "and ask a person to confirm."),
        t(f"- 接着做已有的任务：运行 `{CLI} task use <任务号>`。", f"- Continue an existing task: run `{CLI} task use <task-id>`. ")
        + existing,
    ])


def section_span(text: str, heading: str) -> tuple[int, int] | None:
    m = re.search(rf"(?m)^##\s+{name_pattern(heading)}\s*$", text, re.I)
    if not m:
        return None
    nxt = re.search(r"(?m)^##\s+", text[m.end():])
    return m.end(), (m.end() + nxt.start() if nxt else len(text))


def append_to_section(text: str, heading: str, line: str) -> str:
    span = section_span(text, heading)
    if span is None:
        return text.rstrip("\n") + f"\n\n## {card_name(heading, card_language(text))}\n\n{line}\n"
    start, end = span
    body = text[start:end].rstrip("\n")
    rest = text[end:]
    return text[:start] + body + "\n" + line + "\n" + ("\n" + rest if rest else "")


def set_confirmation(text: str, value: str) -> str:
    span = section_span(text, "需求")
    if span is None:
        raise ValueError(t("任务卡里没有「## 需求」一节", "the task card has no “## Requirement” section"))
    start, end = span
    section = text[start:end]
    label = "确认：" if card_language(text) == "zh" else card_name("确认", "en") + ": "
    line_re = field_line("确认")
    if line_re.search(section):
        section = line_re.sub(lambda m: f"{m.group(1)}{label}{value}", section, count=1)
    else:
        section = section.rstrip("\n") + f"\n- {label}{value}\n\n"
    return text[:start] + section + text[end:]


def git_user(root: Path) -> str:
    try:
        name = git(root, "config", "user.name").strip()
    except subprocess.CalledProcessError:
        name = ""
    return name or os.environ.get("USER", t("未知", "unknown"))


def detect_agent() -> str:
    if os.environ.get("AGENTKIT_AGENT"):
        return os.environ["AGENTKIT_AGENT"]
    if os.environ.get("CLAUDECODE"):
        return "Claude Code"
    return t("未注明 agent", "agent not named")


def current_branch(root: Path) -> str:
    try:
        return git(root, "rev-parse", "--abbrev-ref", "HEAD").strip()
    except subprocess.CalledProcessError:
        return ""


def read_pointer(root: Path) -> tuple[str, str] | None:
    """(task id, branch it was set on). The pointer only counts on that branch, so a switch of branch drops it."""
    pointer = root / POINTER
    if not pointer.exists():
        return None
    lines = pointer.read_text().split()
    return (lines[0], lines[1] if len(lines) > 1 else "") if lines else None


def set_pointer(root: Path, task_id: str | None) -> None:
    pointer = root / POINTER
    if task_id is None:
        pointer.unlink(missing_ok=True)
        return
    pointer.parent.mkdir(parents=True, exist_ok=True)
    pointer.write_text(f"{task_id}\n{current_branch(root)}\n")


def task_new(root: Path, cfg: dict, args: argparse.Namespace) -> int:
    task_id = args.id
    if not TASK_ID_RE.match(task_id):
        print(t("任务号只能用字母、数字、点、横线和下划线，比如 WIP-123",
                "A task id may only use letters, digits, dots, hyphens and underscores, e.g. WIP-123"), file=sys.stderr)
        return 1
    path = card_path(root, cfg, task_id)
    rel = os.path.relpath(path, root)
    if path.exists():
        set_pointer(root, task_id)
        print(t(f"任务卡已经存在：{rel}，已设为当前任务。运行 `{CLI} task show` 查看。",
                f"Task card {rel} already exists; it is now the current task. Run `{CLI} task show` to read it."))
        return 1
    title = " ".join(args.title).strip() or t("（标题）", "(title)")
    template = kit_file("task-card.md").read_text()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(drop_owned_marker(template).replace("{{id}}", task_id).replace("{{title}}", title))
    set_pointer(root, task_id)
    print("\n".join([
        t(f"已新建任务卡 {rel}，并设为当前任务。", f"Created task card {rel} and made it the current task."),
        t("下一步：", "Next:"),
        t(f"1. 让 agent 复述需求、写进这张卡：Claude Code 用 /restate；其他 agent 运行 `{CLI} prompt restate \"<需求>\"`。",
          f"1. Have the agent restate the requirement into this card: /restate in Claude Code; "
          f"other agents run `{CLI} prompt restate \"<requirement>\"`."),
        t(f"2. 人看过之后，在自己的终端里运行 `{CLI} task confirm {task_id}`。",
          f"2. Once a person has read it, they run `{CLI} task confirm {task_id}` in their own terminal."),
    ]))
    return 0


def task_show(root: Path, cfg: dict, args: argparse.Namespace) -> int:
    task_id, how = current_task(root, cfg, args.id, args.base)
    if not task_id:
        print((how + "\n\n" if args.id else "") + no_task_text(root, cfg))
        return 1 if args.id else 0
    path = card_path(root, cfg, task_id)
    text = path.read_text()
    st = card_status(text)
    rel = os.path.relpath(path, root)
    title = st["title"] or task_id
    out = [t(f"当前任务：{title}（`{rel}`，{how}）", f"Current task: {title} (`{rel}`, {how})")]
    if not args.brief:
        out = [t(f"任务卡 `{rel}`（{how}）：", f"Task card `{rel}` ({how}):"), "", text.rstrip(), "", "---"]
    out += [t("状态（agentkit 读出来的）：", "Status (as agentkit reads it):")] + status_lines(task_id, st) + ["", rule_reminder(st)]
    if cfg["tasks_note"]:
        out.append(t(f"本仓库：{cfg['tasks_note']}", f"This repository: {cfg['tasks_note']}"))
    print("\n".join(out))
    return 0


def task_list(root: Path, cfg: dict, args: argparse.Namespace) -> int:
    ids = card_ids(root, cfg)
    if not ids:
        print(no_task_text(root, cfg))
        return 0
    current, _ = current_task(root, cfg)
    mark = {"yes": t("已确认", "confirmed"), "no": t("未确认", "not confirmed"), "stale": t("确认已失效", "sign-off stale")}
    for task_id in ids:
        st = card_status(card_path(root, cfg, task_id).read_text())
        done = sum(1 for state, _ in st["steps"] if state == "done")
        parts = [mark[st["confirmed"]], t(f"拆分 {done}/{len(st['steps'])}", f"steps {done}/{len(st['steps'])}")]
        if st["open"]:
            parts.append(t(f"待拍板 {len(st['open'])}", f"{len(st['open'])} open decision(s)"))
        print(f"{'*' if task_id == current else ' '} {st['title'] or task_id}{t('：', ': ')}{t('，', ', ').join(parts)}")
    return 0


def task_use(root: Path, cfg: dict, args: argparse.Namespace) -> int:
    if args.clear:
        set_pointer(root, None)
        print(t("已清除当前任务。", "Current task cleared."))
        return 0
    if not args.id or args.id not in card_ids(root, cfg):
        print(no_task_text(root, cfg), file=sys.stderr)
        return 1
    set_pointer(root, args.id)
    print(t(f"当前任务：{args.id}。运行 `{CLI} task show` 查看任务卡。",
            f"Current task: {args.id}. Run `{CLI} task show` to read the task card."))
    return 0


def task_confirm(root: Path, cfg: dict, args: argparse.Namespace) -> int:
    if os.environ.get("CLAUDECODE") or not sys.stdin.isatty():
        print(t("确认需求要由人在自己的终端里运行这条命令；agent 不能替人确认。",
                "A person confirms the requirement by running this command in their own terminal; "
                "an agent cannot confirm for them."), file=sys.stderr)
        return 2
    task_id, how = current_task(root, cfg, args.id)
    if not task_id:
        print(how or no_task_text(root, cfg), file=sys.stderr)
        return 1
    path = card_path(root, cfg, task_id)
    text = path.read_text()
    st = card_status(text)
    if st["missing"]:
        missing = join_items(quoted(f) for f in st["missing"])
        print(t(f"需求还缺 {missing}，先补上再确认。", f"The requirement is missing {missing}; fill it in before confirming."),
              file=sys.stderr)
        return 1
    requirement = section_of(card_sections(text), "需求")
    print(t(f"任务 {st['title'] or task_id} 的需求：\n", f"Requirement of task {st['title'] or task_id}:\n"))
    print(strip_comments(requirement).strip())
    if st["open"]:
        print(t(f"\n注意：还有 {len(st['open'])} 件事没拍板（确认需求不代表这些也定了）：",
                f"\nNote: {len(st['open'])} decision(s) are still open (confirming the requirement does not settle them):"))
        for item in st["open"]:
            print(f"  - {item}")
    try:
        answer = input(t("\n这就是你要的吗？输入 y 确认：", "\nIs this what you want? Type y to confirm: ")).strip().lower()
    except (EOFError, KeyboardInterrupt):
        answer = ""
    if answer not in ("y", "yes", "是", "确认"):
        print(t("没有确认。可以让 agent 按你的意见改任务卡，再运行一次。",
                "Not confirmed. Have the agent change the task card as you say, then run this again."))
        return 1
    who, day, fp = git_user(root), time.strftime("%Y-%m-%d"), requirement_fingerprint(requirement)
    value = f"{who}，{day}（需求指纹 {fp}）" if st["lang"] == "zh" else f"{who}, {day} (requirement fingerprint {fp})"
    path.write_text(set_confirmation(text, value))
    rel, steps = os.path.relpath(path, root), quoted(card_name("拆分", st["lang"]))
    print(t(f"已确认。记得把 {rel} 提交；agent 现在可以按{steps}动手了。",
            f"Confirmed. Remember to commit {rel}; the agent can now start on {steps}."))
    return 0


def task_handoff(root: Path, cfg: dict, args: argparse.Namespace) -> int:
    task_id, how = current_task(root, cfg, args.id)
    if not task_id:
        print(how or no_task_text(root, cfg), file=sys.stderr)
        return 1
    path = card_path(root, cfg, task_id)
    text = path.read_text()
    st = card_status(text)
    missing = [k for k in ("做到", "下一步") if not st["handoff"][k]]
    if missing:
        fields = t("、", " and ").join(quoted(card_name(k, st["lang"])) for k in missing)
        handoff = quoted(card_name("交接", st["lang"]))
        print(t(f"先在任务卡的{handoff}里写清{fields}，再运行这条命令。",
                f"Write {fields} under {handoff} in the task card first, then run this command."), file=sys.stderr)
        return 1
    try:
        where = git(root, "rev-parse", "--abbrev-ref", "HEAD").strip() + "@" + git(root, "rev-parse", "--short", "HEAD").strip()
    except subprocess.CalledProcessError:
        where = t("（还没有提交）", "(no commit yet)")
    done, total, nxt = sum(1 for state, _ in st["steps"] if state == "done"), len(st["steps"]), st["handoff"]["下一步"]
    line = f"- {time.strftime('%Y-%m-%d %H:%M')} · {git_user(root)} · {args.agent or detect_agent()} · {where}"
    line += f" · 拆分完成 {done}/{total} · 下一步：{nxt}" if st["lang"] == "zh" else f" · steps done {done}/{total} · next: {nxt}"
    path.write_text(append_to_section(text, "记录", line))
    print(t("已记下交接：\n", "Handoff recorded:\n") + line + "\n\n" + "\n".join(status_lines(task_id, st)))
    return 0


def task_check(root: Path, cfg: dict, args: argparse.Namespace) -> int:
    """For a PR (or the current branch): is there a task card, is the requirement signed off, was the handoff updated?"""
    base = args.base or default_base(root)
    files = changed_files(root, base, worktree=not args.committed_only)
    prefix = tasks_prefix(cfg)
    code = [f for f in files if not f.startswith(prefix)]
    cards = [Path(f).stem for f in card_files(cfg, files) if (root / f).exists()]
    if not cards:
        mentioned = args.branch or ""
        if args.pr_body_file and Path(args.pr_body_file).exists():
            mentioned += "\n" + Path(args.pr_body_file).read_text()
        cards = ids_in(mentioned, card_ids(root, cfg))
    errors: list[str] = []
    warnings: list[str] = []
    report = [t("### 任务卡检查（agentkit task check）", "### Task card check (agentkit task check)"), ""]
    if not cards:
        if code:
            errors.append(t(f"这次改了代码，但找不到任务卡（`{prefix}<任务号>.md`）。新任务运行 `{CLI} task new <任务号> <标题>`；"
                            "已有任务，在 PR 描述里写上任务号。",
                            f"This change touches code but has no task card (`{prefix}<task-id>.md`). For a new task run "
                            f"`{CLI} task new <task-id> <title>`; for an existing task, put its id in the PR description."))
        else:
            report.append(t("这次没有改代码，也没有任务卡，跳过。", "No code changed and no task card; skipped."))
    for task_id in cards:
        rel = f"{prefix}{task_id}.md"
        text = (root / rel).read_text()
        st = card_status(text)
        report += [t(f"#### {st['title'] or task_id}（`{rel}`）", f"#### {st['title'] or task_id} (`{rel}`)"), ""]
        report += status_lines(task_id, st) + [""]
        if st["missing"]:
            missing = join_items(quoted(f) for f in st["missing"])
            errors.append(t(f"{task_id}：需求还缺 {missing}", f"{task_id}: the requirement is missing {missing}"))
        if st["confirmed"] == "no":
            errors.append(t(f"{task_id}：需求还没有人确认（请人运行 `{CLI} task confirm {task_id}`）",
                            f"{task_id}: nobody has confirmed the requirement yet (ask a person to run `{CLI} task confirm {task_id}`)"))
        elif st["confirmed"] == "stale":
            errors.append(t(f"{task_id}：确认之后需求又改过，请人重新确认",
                            f"{task_id}: the requirement changed after it was confirmed; a person must confirm it again"))
        if st["open"]:
            warnings.append(t(f"{task_id}：还有 {len(st['open'])} 件事没拍板", f"{task_id}: {len(st['open'])} decision(s) still open"))
        if code:
            steps, handoff = (quoted(card_name(n, st["lang"])) for n in ("拆分", "交接"))
            if rel not in files:
                warnings.append(t(f"{task_id}：这次改了代码，但任务卡没有更新（拆分状态、交接）",
                                  f"{task_id}: code changed but the task card was not updated ({steps}, {handoff})"))
            else:
                try:
                    before = git(root, "show", f"{base}:{rel}")
                except subprocess.CalledProcessError:
                    before = ""
                if card_status(before)["handoff_text"] == st["handoff_text"]:
                    warnings.append(t(f"{task_id}：任务卡的{handoff}没有更新", f"{task_id}: {handoff} in the task card was not updated"))
    if not cfg["tasks_required"]:
        warnings, errors = errors + warnings, []
    if errors:
        report += [t("**不通过：**", "**Fails:**")] + [f"- {e}" for e in errors] + [""]
    if warnings:
        report += [t("**提醒：**", "**Reminders:**")] + [f"- {w}" for w in warnings] + [""]
    if not errors and not warnings and cards:
        report.append(t("任务卡齐全，需求已确认，交接已更新。", "Task card present, requirement confirmed, handoff updated."))
    text = "\n".join(report).rstrip() + "\n"
    print(text)
    if os.environ.get("GITHUB_ACTIONS"):
        title = t("任务卡", "Task card")
        for e in errors:
            print(f"::error title={title}::{e}")
        for w in warnings:
            print(f"::warning title={title}::{w}")
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a") as f:
            f.write(text)
    return 1 if errors else 0


