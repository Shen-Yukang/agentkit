UI_LANG = "zh"


def set_language(lang: str) -> None:
    global UI_LANG
    UI_LANG = lang


def t(zh: str, en: str) -> str:
    return en if UI_LANG == "en" else zh


def join_items(items) -> str:
    return t("、", ", ").join(items)


def quoted(name: str) -> str:
    return t(f"「{name}」", f"“{name}”")


def risk_word(level: str) -> str:
    return t(RISK_ZH[level], level)


def card_name(name: str, lang: str | None = None) -> str:
    """A task card heading or field (given by its Chinese name) as written in that language."""
    return CARD_NAMES[name] if (lang or UI_LANG) == "en" else name


def name_pattern(name: str) -> str:
    """Regex for a heading or field in either language; English names in any case."""
    return "(?:" + "|".join(re.escape(n) for n in (name, CARD_NAMES.get(name, name))) + ")"


def config_language(data: dict) -> str:
    raw = str(data.get("kit", {}).get("language", "zh")).strip().lower()
    lang = re.split(r"[-_]", raw)[0]  # "en-US", "zh_CN"
    if lang not in LANGUAGES:
        raise ValueError(f'agentkit.toml：[kit] language 只能是 "zh" 或 "en" / must be "zh" or "en" (got "{raw}")')
    return lang


def repo_language(root: Path) -> str:
    """The language agentkit.toml asks for. Never fails, so a guard can still explain a broken config in that language."""
    path = root / "agentkit.toml"
    try:
        text = path.read_text(encoding="utf-8") if path.is_file() else ""
    except (OSError, ValueError):
        return "zh"
    try:
        return config_language(read_toml(text))
    except (ValueError, AttributeError):
        return "en" if re.search(r"""(?m)^\s*language\s*=\s*["']en""", text, re.I) else "zh"


